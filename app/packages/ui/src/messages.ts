export type MessageKey = keyof typeof en;

export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  // The key itself if it's missing (only possible mid hot-reload): one wrong label, not a blank app.
  return (en[key] ?? key).replace(/\{(\w+)\}/g, (m, name: string) => (name === 'product' ? PRODUCT_NAME : String(vars[name] ?? m)));
}
